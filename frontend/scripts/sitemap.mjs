// Regenerates public/sitemap.xml from the content (backend/content): the home page, each
// world, each machine and the About page. Run by `npm run sitemap`, and before every build
// (`prebuild`), so a new machine is listed without anyone having to think of it. No date in
// the file: it only changes when the list of pages changes.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SITE = 'https://aeroreborn.vercel.app'
const content = (name) => JSON.parse(readFileSync(fileURLToPath(new URL(`../../backend/content/${name}`, import.meta.url)), 'utf8'))

const destinations = content('destinations.json')
const missions = new Map(content('missions.json').map((mission) => [mission.id, mission]))
const machines = content('machines.json')

const paths = [
  '/',
  ...destinations.map((destination) => `/explore/${destination.id}`),
  ...machines.map((machine) => {
    const destinationId = missions.get(machine.missionId)?.destinationId
    if (!destinationId) throw new Error(`Machine ${machine.id}: mission ${machine.missionId} has no destination`)
    return `/explore/${destinationId}/${encodeURIComponent(machine.id)}`
  }),
  '/about',
]

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/sitemap.mjs from backend/content (npm run sitemap); do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...paths.map((path) => `  <url><loc>${SITE}${path}</loc></url>`),
  '</urlset>',
  '',
].join('\n')

writeFileSync(fileURLToPath(new URL('../public/sitemap.xml', import.meta.url)), xml)
console.log(`sitemap.xml: ${paths.length} pages`)
